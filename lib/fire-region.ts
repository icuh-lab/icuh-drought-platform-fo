/**
 * 산불위험지수 API 의 시군구 코드와 국가공간정보 시군구 경계(SIG_CD)를 맞추는 규칙.
 *
 * 둘 다 행정표준코드 5자리를 쓰지만 기준 시점이 달라 세 군데가 어긋난다.
 * 어긋나는 지점을 여기 한 곳에 모아두고, 빌드 스크립트와 화면이 같은 규칙을 쓴다.
 */

/**
 * 일반구를 둔 특례시·대도시. API 는 시 단위(41110 수원시)로 지수를 주는데
 * 경계 데이터는 일반구 단위(41111 수원시 장안구)로 쪼개져 있어 구를 시로 합쳐야 한다.
 *
 * 자치구(서울 11215 광진구 등)는 API 도 경계도 같은 단위라 여기 들어오지 않는다.
 * "끝자리가 0이 아니면 일반구" 같은 규칙은 11215·11305·11545 에서 깨지므로 쓰지 않는다.
 */
const MERGED_CITY_CODES = [
  "41110", // 수원시
  "41130", // 성남시
  "41170", // 안양시
  "41270", // 안산시
  "41280", // 고양시
  "41460", // 용인시
  "43110", // 청주시
  "44130", // 천안시
  "47110", // 포항시
  "48120" // 창원시
] as const;

/**
 * 행정구역 개편으로 코드가 바뀐 지역. 경계 데이터가 옛 코드를 쓰므로 새 코드로 옮긴다.
 * - 51xxx: 강원특별자치도 출범(2023-06)으로 42xxx 에서 이동
 * - 27720: 군위군이 경북(47720)에서 대구로 편입(2023-07)
 */
const RENAMED_REGION_CODES: Record<string, string> = {
  "42110": "51110",
  "42130": "51130",
  "42150": "51150",
  "42170": "51170",
  "42190": "51190",
  "42210": "51210",
  "42230": "51230",
  "42720": "51720",
  "42730": "51730",
  "42750": "51750",
  "42760": "51760",
  "42770": "51770",
  "42780": "51780",
  "42790": "51790",
  "42800": "51800",
  "42810": "51810",
  "42820": "51820",
  "42830": "51830",
  "47720": "27720"
};

/** 경계 데이터의 일반구 코드이면 소속 시 코드를, 아니면 null 을 준다. */
export function parentCityCode(sigCode: string): string | null {
  const parent = MERGED_CITY_CODES.find((code) => code !== sigCode && sigCode.startsWith(code.slice(0, 4)));
  return parent ?? null;
}

/** 경계 데이터의 SIG_CD 를 API 가 쓰는 시군구 코드로 옮긴다. */
export function canonicalRegionCode(sigCode: string): string {
  return RENAMED_REGION_CODES[sigCode] ?? parentCityCode(sigCode) ?? sigCode;
}

/** 시군구 코드 앞 두 자리가 시도를 가리킨다. 51·52 는 특별자치도 전환으로 늘어난 코드다. */
const SIDO_BY_PREFIX: Record<string, string> = {
  "11": "서울",
  "26": "부산",
  "27": "대구",
  "28": "인천",
  "29": "광주",
  "30": "대전",
  "31": "울산",
  "36": "세종",
  "41": "경기",
  "42": "강원",
  "43": "충북",
  "44": "충남",
  "45": "전북",
  "46": "전남",
  "47": "경북",
  "48": "경남",
  "50": "제주",
  "51": "강원",
  "52": "전북"
};

/** 모르는 코드면 빈 문자열. 화면은 시도 라벨 없이 지역명만 보여준다. */
export function sidoName(regionCode: string): string {
  return SIDO_BY_PREFIX[regionCode.slice(0, 2)] ?? "";
}

/** 지도에 그릴 시군구 경계. 빌드 스크립트가 굽고 public/korea-sigungu.json 으로 나간다. */
export type FireRegionMap = {
  /** viewBox 크기. 경계 좌표를 이 안에 맞춰 미리 투영해 두었다. */
  width: number;
  height: number;
  /** 시군구 코드 -> SVG path 의 d 속성 */
  paths: Record<string, string>;
};
