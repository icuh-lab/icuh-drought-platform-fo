/**
 * 개편으로 이름까지 바뀐 지역. 경계 데이터의 옛 이름 대신 이 이름을 쓴다.
 * 코드만 옮긴 지역(목포시 등)은 이름이 그대로라 여기 들어오지 않는다.
 */
export const RENAMED_REGION_NAMES: Record<string, string> = {
  "28125": "제물포구",
  "28275": "서해구"
};

/** 경계 데이터의 일반구 코드이면 소속 시 코드를, 아니면 null 을 준다. */
export function parentCityCode(sigCode: string): string | null {
  const parent = MERGED_CITY_CODES.find((code) => code !== sigCode && sigCode.startsWith(code.slice(0, 4)));
  return parent ?? null;
}

/** 경계 데이터의 SIG_CD 를 API 가 쓰는 시군구 코드로 옮긴다. */
export function canonicalRegionCode(sigCode: string): string {
  return RENAMED_REGION_CODES[sigCode] ?? parentCityCode(sigCode) ?? sigCode;
}

